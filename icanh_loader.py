import requests
from collections import defaultdict
from qgis.core import (
    QgsProject, QgsVectorLayer, QgsFeature, QgsField, QgsGeometry, QgsPointXY
)
from PyQt5.QtCore import QVariant

print("🧹 Clearing canvas...")
QgsProject.instance().removeAllMapLayers()

base_url = "https://geovector.icanh.gov.co/server/rest/services/pruebas/Sitio_Hallazgos/FeatureServer"

# 1. FETCH WITH PAGINATION
def fetch_all_features(layer_id):
    all_features = []
    offset = 0
    limit = 2000
    while True:
        url = f"{base_url}/{layer_id}/query?where=1%3D1&outFields=*&f=json&resultOffset={offset}&resultRecordCount={limit}"
        res = requests.get(url).json()
        features = res.get("features", [])
        all_features.extend(features)
        if len(features) < limit:
            break
        offset += limit
    return all_features

print("📥 Downloading all API layers (this will take a moment)...")
sites_data = fetch_all_features(0)
context_data = fetch_all_features(2)
dating_data = fetch_all_features(4)
sources_data = fetch_all_features(3)
collections_data = fetch_all_features(5)

# 2. MAP RELATIONS
print("🔗 Linking data dynamically...")
ctx_uuid_to_site = {}
ctx_int_to_site = {}

for c in context_data:
    attrs = c["attributes"]
    site_uuid = attrs.get("parentglobalid")
    if site_uuid:
        if attrs.get("globalid"): ctx_uuid_to_site[attrs["globalid"]] = site_uuid
        if attrs.get("id_contexto"): ctx_int_to_site[attrs["id_contexto"]] = site_uuid

# The Integration: We use a nested dictionary to hold every field dynamically
# Format: site_data[site_uuid]["Prefix_FieldName"] = [val1, val2]
site_data = defaultdict(lambda: defaultdict(list))

# Fields to ignore (database metadata)
ignore_fields = ['objectid', 'globalid', 'parentglobalid', 'id_contexto', 
                 'created_user', 'created_date', 'last_edited_user', 'last_edited_date',
                 'id_sitio', 'id_fuentes', 'id_coleccion', 'id_datacion']

# Process Contexto
for c in context_data:
    site_uuid = c["attributes"].get("parentglobalid")
    if not site_uuid: continue
    for k, v in c["attributes"].items():
        if k not in ignore_fields and v is not None and str(v).strip() != "":
            site_data[site_uuid][f"Ctx_{k}"].append(str(v))

# Process Datacion
for d in dating_data:
    ctx_uuid = d["attributes"].get("parentglobalid")
    site_uuid = ctx_uuid_to_site.get(ctx_uuid)
    if not site_uuid: continue
    for k, v in d["attributes"].items():
        if k not in ignore_fields and v is not None and str(v).strip() != "":
            site_data[site_uuid][f"Dat_{k}"].append(str(v))

# Process Fuentes (Links via Integer id_contexto)
for f in sources_data:
    ctx_int = f["attributes"].get("id_contexto")
    site_uuid = ctx_int_to_site.get(ctx_int)
    if not site_uuid: continue
    for k, v in f["attributes"].items():
        if k not in ignore_fields and v is not None and str(v).strip() != "":
            site_data[site_uuid][f"Fue_{k}"].append(str(v))

# Process Colecciones
for col in collections_data:
    ctx_uuid = col["attributes"].get("parentglobalid")
    site_uuid = ctx_uuid_to_site.get(ctx_uuid)
    if not site_uuid: continue
    for k, v in col["attributes"].items():
        if k not in ignore_fields and v is not None and str(v).strip() != "":
            site_data[site_uuid][f"Col_{k}"].append(str(v))

# 3. DYNAMICALLY BUILD THE LAYER
print("🗺️ Building the massive spatial layer...")
vlayer = QgsVectorLayer("Point?crs=EPSG:4326", "Sitios_ICANH", "memory")
prov = vlayer.dataProvider()

# Start with the basic spatial fields
base_fields = [
    QgsField("ID_Sitio", QVariant.String),
    QgsField("Site_Name", QVariant.String),
    QgsField("Municipality", QVariant.String),
    QgsField("Department", QVariant.String)
]
prov.addAttributes(base_fields)

# Find all unique dynamic fields generated by our loop
dynamic_keys = set()
for site_uuid, fields in site_data.items():
    dynamic_keys.update(fields.keys())
    
sorted_keys = sorted(list(dynamic_keys))

# Add all dynamic fields to the layer
dynamic_fields = [QgsField(k, QVariant.String) for k in sorted_keys]
prov.addAttributes(dynamic_fields)
vlayer.updateFields()

features = []
for site in sites_data:
    attrs = site["attributes"]
    geom = site.get("geometry")
    
    site_id = attrs.get("globalid")
    x = geom.get("x") if geom else attrs.get("longitud")
    y = geom.get("y") if geom else attrs.get("latitud")
        
    if not x or not y or not site_id: continue
    
    f = QgsFeature()
    f.setGeometry(QgsGeometry.fromPointXY(QgsPointXY(x, y)))
    
    # Base attributes
    row_attrs = [
        attrs.get("id_sitio"),
        attrs.get("nombre_arqueologico"),
        attrs.get("municipio"),
        attrs.get("departamento")
    ]
    
    # Dynamic attributes
    for key in sorted_keys:
        vals = site_data[site_id].get(key, [])
        # Join unique values with comma
        row_attrs.append(", ".join(sorted(set(vals))) if vals else "")
        
    f.setAttributes(row_attrs)
    features.append(f)

prov.addFeatures(features)
QgsProject.instance().addMapLayer(vlayer)

print(f"\n✅ DONE! Successfully loaded {len(features)} sites with ALL contextual fields.")
print("👉 Open the Attribute Table, scroll right, and hide the columns you don't need.")
